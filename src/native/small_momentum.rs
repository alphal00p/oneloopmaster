//! Two-point function at small external momentum without cancellation.
//!
//! The general B0 expression contains terms of size `max(m0², m1²)/p²` that
//! cancel to O(1): at `p² = 1e-10` against `m² = 3e4` (a numerically
//! lightlike gluon leg of a top loop) binary64 keeps only two digits. This
//! module evaluates the momentum dependence of the finite part,
//!
//! `B0(p²) − B0(0) = −∫₀¹ dx ln(1 − x(1−x) p² / D(x))`,
//! `D(x) = (1−x) m0² + x m1²`,
//!
//! from the zeros of `L(x) = D(x) − x(1−x) p²`, so that every term is
//! explicitly proportional to `p²`. Order the masses so `|m0²| ≥ |m1²|` (B0
//! is symmetric) and write `a = m0²`, `t = p²/a`, `r0 = 1 − m1²/m0²` (`1/r0`
//! is the zero of `D`); `r1, r2` are the reciprocal zeros of `L`,
//! `r1 + r2 = r0 + t` and `r1 r2 = t`. With
//! `F(y) = ∫₀¹ ln(1 − x/y) dx = −Σ_{n≥1} y^-n / (n(n+1))`,
//! the shift is `−[F(1/r1) + F(1/r2) − F(1/r0)]`.
//!
//! * Comparable masses (all `|r| ≤ 3/4`): the shift is
//!   `Σ_{n≥1} d_n / (n(n+1))` with `d_n = r1^n + r2^n − r0^n`, generated by
//!   `d_0 = 1`, `d_1 = t`,
//!   `d_n = (r0 + t) d_{n−1} − t d_{n−2} − t r0^{n−2} m1²/m0²`,
//!   in which every term carries an explicit factor `t`.
//! * Hierarchical masses (`|r0| > 1/2`, so the zero `x0 = 1/r0` of `D` lies
//!   within distance 1 of the interval): the zero `x1 = x0 + δ` of `L` next
//!   to `x0` is found from a quadratic for `δ` itself, and
//!   `F(x1) − F(x0) = (1 − x1)[log1p(δ/(x0−1)) − log1p(δ/x0)] − δ ln(m1²/m0²)`;
//!   the far zero `x2 = m0²/(p² x1)` enters through the series for `F`.
//!
//! Outside `|t| ≤ 1/16` (the general expression then loses at most a few
//! bits) or when neither representation converges fast, the caller keeps the
//! general expression.

use super::primitives::{C, NativeFloat, add, inverse, log, mul, sqrt};

fn modulus<T: NativeFloat>(z: &C<T>) -> T {
    NativeFloat::hypot(&z.re, &z.im)
}

fn sub<T: NativeFloat>(a: &C<T>, b: &C<T>) -> C<T> {
    C::new(a.re.clone() - &b.re, a.im.clone() - &b.im)
}

fn div<T: NativeFloat>(a: &C<T>, b: &C<T>) -> C<T> {
    mul(a, &inverse(b))
}

fn scale<T: NativeFloat>(a: &C<T>, factor: &T) -> C<T> {
    C::new(a.re.clone() * factor, a.im.clone() * factor)
}

fn real<T: NativeFloat>(prototype: &T, value: i64) -> C<T> {
    C::new(prototype.from_i64(value), prototype.zero())
}

/// `ln(1 + z)` for `|z| <= 1/8` by its alternating series, else `ln(1 + z)`.
fn log1p<T: NativeFloat>(z: &C<T>, tolerance: &T) -> C<T> {
    let prototype = &z.re;
    let eighth = prototype.one() / prototype.from_i64(8);
    if modulus(z) > eighth {
        return log(&add(&real(prototype, 1), z));
    }
    let mut power = z.clone();
    let mut sum = z.clone();
    for n in 2..4096i64 {
        power = mul(&power, z);
        let term = scale(&power, &(prototype.one() / prototype.from_i64(n)));
        sum = if n % 2 == 0 { sub(&sum, &term) } else { add(&sum, &term) };
        if modulus(&term) <= modulus(&sum) * tolerance {
            break;
        }
    }
    sum
}

/// `−F(1/r) = Σ_{n≥1} r^n / (n(n+1))` for `|r| < 1`.
fn far_zero<T: NativeFloat>(r: &C<T>, tolerance: &T) -> Option<C<T>> {
    let prototype = &r.re;
    let mut power = r.clone();
    let mut sum = scale(r, &(prototype.one() / prototype.from_i64(2)));
    if modulus(r).is_zero() {
        return Some(sum);
    }
    for n in 2..65536i64 {
        power = mul(&power, r);
        let term = scale(&power, &(prototype.one() / prototype.from_i64(n * (n + 1))));
        sum = add(&sum, &term);
        if modulus(&term) <= modulus(&sum) * tolerance {
            return Some(sum);
        }
    }
    None
}

/// Finite-part shift `B0(p², m0², m1²) − B0(0, m0², m1²)` for small `|p²|`,
/// accurate to about `tolerance` relative (pass roughly the working
/// precision's unit roundoff), or `None` where the caller should keep the
/// general expression. Poles do not depend on `p²`.
pub fn b0_momentum_shift<T: NativeFloat>(
    p2: &C<T>,
    m0: &C<T>,
    m1: &C<T>,
    tolerance: &T,
) -> Option<C<T>> {
    let prototype = &p2.re;
    let one = real(prototype, 1);
    let (a, c) = if modulus(m0) >= modulus(m1) { (m0, m1) } else { (m1, m0) };
    let size = modulus(a);
    if size.is_zero() || !size.is_finite() || modulus(p2).is_zero() {
        return None;
    }
    let t = div(p2, a);
    let ratio = div(c, a); // m1²/m0², |ratio| <= 1
    let r0 = sub(&one, &ratio);
    let sixteenth = prototype.one() / prototype.from_i64(16);
    if modulus(&t) > sixteenth {
        return None;
    }
    // Reciprocal zeros of L: r^2 - (r0 + t) r + t = 0, larger root first.
    let s = add(&r0, &t);
    let disc = sqrt(&sub(&mul(&s, &s), &scale(&t, &prototype.from_i64(4))));
    let (plus, minus) = (add(&s, &disc), sub(&s, &disc));
    let q = if modulus(&plus) >= modulus(&minus) { plus } else { minus };
    let half = prototype.one() / prototype.from_i64(2);
    let r1 = scale(&q, &half);
    let r2 = if modulus(&r1).is_zero() { r1.clone() } else { div(&t, &r1) };
    let largest = [modulus(&r0), modulus(&r1), modulus(&r2)]
        .into_iter()
        .fold(prototype.zero(), |acc, x| if x > acc { x } else { acc });
    let three_quarters = prototype.from_i64(3) / prototype.from_i64(4);
    if largest <= three_quarters {
        // d_n = r1^n + r2^n - r0^n with explicit factors of t.
        let mut previous2 = one.clone(); // d_0
        let mut previous = t.clone(); // d_1
        let mut sum = scale(&t, &half);
        let mut r0_power = one.clone(); // r0^(n-2)
        let t_ratio = mul(&t, &ratio);
        for n in 2..65536i64 {
            let d = sub(
                &sub(&mul(&s, &previous), &mul(&t, &previous2)),
                &mul(&t_ratio, &r0_power),
            );
            let term = scale(&d, &(prototype.one() / prototype.from_i64(n * (n + 1))));
            sum = add(&sum, &term);
            // Terms shrink at least like largest^n; stop once below the
            // tolerance after the slowest geometric tail is accounted for.
            if modulus(&term) <= modulus(&sum) * tolerance * (prototype.one() - &largest) {
                return Some(sum);
            }
            previous2 = previous;
            previous = d;
            r0_power = mul(&r0_power, &r0);
        }
        return None;
    }
    if modulus(&r0) <= half {
        return None;
    }
    // Hierarchical masses: x0 = 1/r0 = a/(a - c), x0 - 1 = c/(a - c).
    let gap = sub(a, c);
    let x0 = div(a, &gap);
    let x0_minus_one = div(c, &gap);
    let b = sub(c, a);
    // p² δ² + B δ + p² x0 (x0 - 1) = 0, B = b + p² (2 x0 - 1); small root.
    let big_b = add(&b, &mul(p2, &sub(&scale(&x0, &prototype.from_i64(2)), &one)));
    let constant = mul(p2, &mul(&x0, &x0_minus_one));
    let disc = sqrt(&sub(&mul(&big_b, &big_b), &scale(&mul(p2, &constant), &prototype.from_i64(4))));
    let (plus, minus) = (add(&big_b, &disc), sub(&big_b, &disc));
    let den = if modulus(&plus) >= modulus(&minus) { plus } else { minus };
    if modulus(&den).is_zero() {
        return None;
    }
    let minus_two = prototype.from_i64(-2);
    let delta = div(&scale(&constant, &minus_two), &den);
    let delta_over_x0 = div(&scale(&mul(p2, &x0_minus_one), &minus_two), &den);
    let delta_over_gap = div(&scale(&mul(p2, &x0), &minus_two), &den);
    let eighth = prototype.one() / prototype.from_i64(8);
    if modulus(&delta_over_x0) > eighth || modulus(&delta_over_gap) > eighth {
        return None;
    }
    let x1 = add(&x0, &delta);
    let far = mul(&t, &x1); // 1/x2 = p² x1 / m0²
    if modulus(&far) > half {
        return None;
    }
    let mut near = mul(
        &sub(&one, &x1),
        &sub(&log1p(&delta_over_gap, tolerance), &log1p(&delta_over_x0, tolerance)),
    );
    if !modulus(&delta).is_zero() {
        near = sub(&near, &mul(&delta, &log(&ratio)));
    }
    // Shift = -[F(x1) - F(x0)] - F(x2).
    let far = far_zero(&far, tolerance)?;
    Some(add(&sub(&real(prototype, 0), &near), &far))
}
